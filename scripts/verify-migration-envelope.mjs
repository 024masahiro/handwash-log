import assert from 'node:assert/strict';
import {generateKeyPairSync} from 'node:crypto';
import {encryptBackup,decryptBackup,sha256} from './migration-envelope.mjs';
import {resumeStage} from './free-backend-operations.mjs';
const {privateKey,publicKey}=generateKeyPairSync('rsa',{modulusLength:2048});
const pem=publicKey.export({type:'spki',format:'pem'}).toString();
const backup={staff:[{id:'staff-test',name:'移行確認',login_email:'staff@example.invalid',password_hash:'0123456789abcdef0123456789abcdef:'+ 'a'.repeat(64),is_admin:0}],washes:[{id:'wash-test',staff_id:'staff-test',washed_at:1}]};
const envelope=encryptBackup(backup,pem);
assert.deepEqual(decryptBackup(envelope,privateKey),backup);
assert.equal(envelope.keyFingerprint,sha256(pem));
assert(!JSON.stringify(envelope).includes('staff@example.invalid'));
assert(!JSON.stringify(envelope).includes(backup.staff[0].password_hash));
assert.notEqual(encryptBackup(backup,pem).ciphertext,envelope.ciphertext);
for(const update of [{projectId:'another-project'},{purpose:'another-purpose'},{iv:Buffer.alloc(12).toString('base64')},{tag:Buffer.alloc(16).toString('base64')},{ciphertext:Buffer.from('tampered').toString('base64')},{wrappedKey:Buffer.alloc(256).toString('base64')},{extra:'untrusted'}])assert.throws(()=>decryptBackup({...envelope,...update},privateKey),/照合/);
const other=generateKeyPairSync('rsa',{modulusLength:2048});assert.throws(()=>decryptBackup(envelope,other.privateKey),/照合/);
assert.equal(resumeStage(undefined,'a'),'new');
for(const state of ['auth-importing','records-importing','importing','complete'])assert.equal(resumeStage({digest:'a',state},'a'),state);
assert.throws(()=>resumeStage({digest:'different',state:'complete'},'a'),/別の/);
assert.throws(()=>resumeStage({digest:'a',state:'unexpected'},'a'),/移行状態/);
console.log('Encrypted migration checks passed: private-data round trip, randomized encryption, project/key binding and tamper rejection.');
